"""S&P 500 gap scanner -> watchlist.txt (top 20 gappers).

    python morning_prefilter.py --dry-run
    python morning_prefilter.py --min-gap 1.0      # flat day testing
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from zoneinfo import ZoneInfo

import pandas as pd
import yfinance as yf

from src.common import WATCHLIST_PATH, now_et
from src.marketdata import yahoo_symbol
from src.notify import notify
from src.sp500_tickers import SP500_TICKERS

DEFAULT_MIN_GAP_PCT = 3.0
DEFAULT_MIN_PRICE = 3.0
MAX_SURVIVORS = 20
ET = ZoneInfo("America/New_York")


def screen(data: pd.DataFrame, tickers: list[str], min_gap: float, min_price: float, today) -> dict:
    survivors, below_gap, below_price, failed, stale = [], [], [], [], []
    for ibkr_sym in tickers:
        y = yahoo_symbol(ibkr_sym)
        try:
            bars = data[y].dropna(subset=["Close"]) if isinstance(data.columns, pd.MultiIndex) else data.dropna(subset=["Close"])
            if len(bars) < 2:
                raise IndexError("fewer than 2 bars")
            # Before the open (or on a holiday) Yahoo's last bar is still yesterday; using it would
            # compute yesterday's gap. Only screen when today's bar exists.
            if pd.Timestamp(bars.index[-1]).date() != today:
                stale.append(ibkr_sym)
                continue
            yesterday_close = float(bars.iloc[-2]["Close"])
            today_open = float(bars.iloc[-1]["Open"])
            today_close = float(bars.iloc[-1]["Close"])  # live print during market hours
            gap_pct = (today_close - yesterday_close) / yesterday_close * 100
        except (KeyError, IndexError, ValueError, ZeroDivisionError):
            failed.append(ibkr_sym)
            continue
        if today_close < min_price:
            below_price.append(ibkr_sym)
        elif gap_pct < min_gap:
            below_gap.append(ibkr_sym)
        else:
            survivors.append({"ticker": ibkr_sym, "gap_pct": gap_pct, "open": today_open, "prev": yesterday_close})
    survivors.sort(key=lambda s: s["gap_pct"], reverse=True)
    return {"survivors": survivors, "below_gap": below_gap, "below_price": below_price, "failed": failed, "stale": stale}


def write_watchlist(survivors: list[dict], total: int, min_gap: float, min_price: float) -> None:
    stamp = now_et().strftime("%Y-%m-%d %H:%M %Z")
    lines = [
        f"# Auto-generated by morning_prefilter.py at {stamp}",
        f"# Filters: gap >= {min_gap}%, price >= ${min_price}",
        "# Source: yfinance (screening only); IBKR handles execution",
        f"# Survivors: {len(survivors)} (capped at {MAX_SURVIVORS}) of {total}",
        "#",
        "# ticker  # gap +X.XX%  open $X.XX  prev $X.XX",
    ]
    for s in survivors:
        lines.append(f"{s['ticker']}  # gap {s['gap_pct']:+.2f}%  open ${s['open']:.2f}  prev ${s['prev']:.2f}")
    tmp = WATCHLIST_PATH.with_suffix(".tmp")
    tmp.write_text("\n".join(lines) + "\n", encoding="utf-8")
    tmp.replace(WATCHLIST_PATH)  # atomic: cycle.py never reads a half-written file


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--min-gap", type=float, default=DEFAULT_MIN_GAP_PCT)
    ap.add_argument("--min-price", type=float, default=DEFAULT_MIN_PRICE)
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    started = time.monotonic()
    hhmm = now_et().strftime("%H:%M ET")
    tickers = list(SP500_TICKERS)
    total = len(tickers)
    try:
        data = yf.download(
            tickers=" ".join(yahoo_symbol(t) for t in tickers),
            period="2d",
            interval="1d",
            group_by="ticker",
            threads=5,  # >5 exhausts file descriptors under Task Scheduler
            progress=False,
            auto_adjust=True,
            timeout=20,
        )
    except Exception as exc:
        data = pd.DataFrame()
        err = f"yf.download raised {exc!r}"
    else:
        err = "yf.download returned an empty dataframe"
    if data is None or data.empty:
        print(json.dumps({"success": False, "error": err}))
        if not args.dry_run:
            notify(f"Prefilter FAILED {hhmm}", err, "high")
        return 1

    res = screen(data, tickers, args.min_gap, args.min_price, now_et().date())
    survivors = res["survivors"][:MAX_SURVIVORS]
    failed = len(res["failed"])
    elapsed = round(time.monotonic() - started, 1)

    alert = None
    if failed / total >= 0.95:
        alert = "ALERT: Yahoo-wide failure suspected; check yfinance changelog"
    elif failed / total >= 0.30:
        alert = f"ALERT: yfinance degradation (failed {failed}/{total})"
    if len(res["stale"]) == total:
        alert = "ALERT: no bars for today yet (pre-market, weekend or market holiday); watchlist not updated"
    if alert:
        print(alert, file=sys.stderr)

    if not args.dry_run and len(res["stale"]) < total:
        write_watchlist(survivors, total, args.min_gap, args.min_price)

    summary = {
        "success": True,
        "total_screened": total,
        "survivors_count": len(survivors),
        "below_gap": len(res["below_gap"]),
        "below_price": len(res["below_price"]),
        "failed": failed,
        "stale": len(res["stale"]),
        "elapsed_seconds": elapsed,
        "top_20_survivors": [f"{s['ticker']} ({s['gap_pct']:+.2f}%)" for s in survivors],
        "watchlist_path": str(WATCHLIST_PATH),
    }
    print(json.dumps(summary, indent=2))

    if not args.dry_run:
        if alert:
            notify(f"Prefilter ALERT {hhmm}", alert, "high")
        bullets = "\n".join(f"- {s['ticker']} {s['gap_pct']:+.2f}%" for s in survivors) or "(none)"
        notify(f"Prefilter {hhmm}", f"{len(survivors)}/{total} survivors in {elapsed}s\n{bullets}", "default")
    return 0


if __name__ == "__main__":
    sys.exit(main())
